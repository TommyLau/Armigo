ARMIGO_TEST(emission, scale_bias_matches_expected_source) {
    const MslEmitResult result = emit_msl(scale_bias_program());
    ARMIGO_CHECK(result.ok());
    const std::string expected =
        "// Generated by the Armigo shader foundation. Do not edit.\n"
        "#include <metal_stdlib>\n"
        "\n"
        "// Forbid reassociation, contraction into FMA, and assumptions\n"
        "// about NaN, infinity, and signed zero.\n"
        "#pragma METAL fp math_mode(safe)\n"
        "#pragma METAL fp contract(off)\n"
        "\n"
        "struct armigo_parameters_scale_bias {\n"
        "    float slot0;\n"
        "    float slot1;\n"
        "};\n"
        "\n"
        "kernel void armigo_kernel_scale_bias(\n"
        "    constant armigo_parameters_scale_bias& parameters [[buffer(0)]],\n"
        "    device const float* input0 [[buffer(1)]],\n"
        "    device float* output0 [[buffer(2)]],\n"
        "    constant uint& element_count [[buffer(3)]],\n"
        "    uint invocation [[thread_position_in_grid]])\n"
        "{\n"
        "    if (invocation >= element_count) {\n"
        "        return;\n"
        "    }\n"
        "    const float v0 = input0[invocation];\n"
        "    const float v1 = parameters.slot0;\n"
        "    const float v2 = v0 * v1;\n"
        "    const float v3 = parameters.slot1;\n"
        "    const float v4 = v2 + v3;\n"
        "    output0[invocation] = v4;\n"
        "}\n";
    ARMIGO_CHECK_EQ(result.kernel.source, expected);
    ARMIGO_CHECK_EQ(result.kernel.entry_point, std::string("armigo_kernel_scale_bias"));
    ARMIGO_CHECK_EQ(result.kernel.parameter_block_size, 8u);
}

ARMIGO_TEST(emission, isolates_standard_library_names) {
    for (const char* name : {"NAN", "INFINITY", "FLT_MAX", "assert",
                             "packed_float3", "complex"}) {
        Program program = scale_bias_program();
        program.entry_point = name;
        const MslEmitResult result = emit_msl(program);
        ARMIGO_CHECK(result.ok());
        ARMIGO_CHECK_EQ(result.kernel.entry_point, std::string("armigo_kernel_") + name);
        ARMIGO_CHECK(contains(result.kernel.source,
                              "kernel void " + result.kernel.entry_point + "("));
    }
}

ARMIGO_TEST(emission, binding_layout) {
    const MslEmitResult result = emit_msl(mixed_types_program());
    ARMIGO_CHECK(result.ok());
    const std::vector<MslBinding> expected = {
        {MslBindingKind::parameters, 0, 0, ScalarType::u32},
        {MslBindingKind::input, 0, 1, ScalarType::f32},
        {MslBindingKind::input, 1, 2, ScalarType::u32},
        {MslBindingKind::output, 0, 3, ScalarType::f32},
        {MslBindingKind::output, 1, 4, ScalarType::u32},
        {MslBindingKind::output, 2, 5, ScalarType::u32},
        {MslBindingKind::output, 3, 6, ScalarType::u32},
        {MslBindingKind::element_count, 0, 7, ScalarType::u32},
    };
    ARMIGO_CHECK(result.kernel.bindings == expected);
    ARMIGO_CHECK_EQ(result.kernel.parameter_block_size, 8u);

    const std::string& source = result.kernel.source;
    ARMIGO_CHECK(contains(source, "    float slot0;\n    uint slot1;\n"));
    ARMIGO_CHECK(contains(source, "device const uint* input1 [[buffer(2)]],"));
    ARMIGO_CHECK(contains(source, "device uint* output3 [[buffer(6)]],"));
    ARMIGO_CHECK(contains(source, "constant uint& element_count [[buffer(7)]],"));

    // Without parameters there is no parameter block or struct, and the first
    // input takes buffer 0.
    const MslEmitResult plain = emit_msl(sum_left_program());
    ARMIGO_CHECK(plain.ok());
    ARMIGO_CHECK(!contains(plain.kernel.source, "struct"));
    ARMIGO_CHECK(!contains(plain.kernel.source, "parameters"));
    ARMIGO_CHECK(contains(plain.kernel.source,
                          "device const float* input0 [[buffer(0)]],"));
    ARMIGO_CHECK_EQ(plain.kernel.parameter_block_size, 0u);
    ARMIGO_CHECK_EQ(plain.kernel.bindings.size(), 5u);
}

ARMIGO_TEST(emission, constants_use_exact_bit_patterns) {
    ProgramBuilder b("constants");
    b.add_output(ScalarType::f32);
    b.add_output(ScalarType::u32);
    const ValueId tenth = b.constant_f32(0.1f);
    const ValueId negative_zero = b.constant_f32(-0.0f);
    const ValueId tiny = b.constant_f32(bits_f32(0x00000001u));
    const ValueId sum = b.fadd(b.fadd(tenth, negative_zero), tiny);
    b.store_output(ScalarType::f32, 0, sum);
    b.store_output(ScalarType::u32, 1, b.constant_u32(4294967295u));
    const MslEmitResult result = emit_msl(b.program());
    ARMIGO_CHECK(result.ok());
    const std::string& source = result.kernel.source;
    ARMIGO_CHECK(contains(
        source, "    const float v0 = as_type<float>(0x3dcccccdu); // 0.1\n"));
    ARMIGO_CHECK(contains(
        source, "    const float v1 = as_type<float>(0x80000000u); // -0\n"));
    ARMIGO_CHECK(contains(
        source, "    const float v2 = as_type<float>(0x00000001u); // 1e-45\n"));
    ARMIGO_CHECK(contains(source, "    const uint v6 = 4294967295u;\n"));
}

ARMIGO_TEST(emission, preserves_operation_and_operand_order) {
    const MslEmitResult left = emit_msl(sum_left_program());
    const MslEmitResult right = emit_msl(sum_right_program());
    ARMIGO_CHECK(left.ok() && right.ok());
    ARMIGO_CHECK(contains(left.kernel.source,
                          "    const float v3 = v0 + v1;\n"
                          "    const float v4 = v3 + v2;\n"));
    ARMIGO_CHECK(contains(right.kernel.source,
                          "    const float v3 = v1 + v2;\n"
                          "    const float v4 = v0 + v3;\n"));

    // Operands are never swapped, even for commutative operations.
    ProgramBuilder b("swapped");
    b.add_input(ScalarType::f32);
    b.add_input(ScalarType::f32);
    b.add_output(ScalarType::f32);
    const ValueId x = b.load_input(ScalarType::f32, 0);
    const ValueId y = b.load_input(ScalarType::f32, 1);
    const ValueId product = b.fmul(y, x);
    b.store_output(ScalarType::f32, 0, b.fadd(product, y));
    const MslEmitResult swapped = emit_msl(b.program());
    ARMIGO_CHECK(swapped.ok());
    ARMIGO_CHECK(contains(swapped.kernel.source, "const float v2 = v1 * v0;"));
    ARMIGO_CHECK(contains(swapped.kernel.source, "const float v3 = v2 + v1;"));

    // Every arithmetic statement holds exactly one operator, so the compiler
    // receives no compound expression to regroup.
    const std::string& source = left.kernel.source;
    ARMIGO_CHECK_EQ(count_of(source, " + "), 2u);
    ARMIGO_CHECK_EQ(count_of(source, " * "), 0u);
    ARMIGO_CHECK_EQ(count_of(source, "fma"), 0u);
    ARMIGO_CHECK_EQ(count_of(source, "#pragma METAL fp math_mode(safe)\n"), 1u);
    ARMIGO_CHECK_EQ(count_of(source, "#pragma METAL fp contract(off)\n"), 1u);
}

