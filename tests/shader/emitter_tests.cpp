ARMIGO_TEST(emission, deterministic_output) {
    for (const NamedProgram& fixture : msl_fixtures()) {
        const MslEmitResult first = emit_msl(fixture.program);
        const MslEmitResult second = emit_msl(fixture.program);
        // A program rebuilt from scratch emits identical text too.
        Program copy;
        copy.entry_point = fixture.program.entry_point;
        copy.parameters = fixture.program.parameters;
        copy.inputs = fixture.program.inputs;
        copy.outputs = fixture.program.outputs;
        for (const Instruction& inst : fixture.program.body) {
            copy.body.push_back(inst);
        }
        const MslEmitResult third = emit_msl(copy);
        ARMIGO_CHECK(first.ok() && second.ok() && third.ok());
        ARMIGO_CHECK_EQ(first.kernel.source, second.kernel.source);
        ARMIGO_CHECK_EQ(first.kernel.source, third.kernel.source);
        ARMIGO_CHECK(first.kernel.bindings == second.kernel.bindings);
        ARMIGO_CHECK(contains(first.kernel.source,
                              "kernel void " + first.kernel.entry_point + "(\n"));
    }
}

ARMIGO_TEST(emission, rejects_invalid_programs) {
    Program program = scale_bias_program();
    program.body[2].operand1 = ValueId{17};
    const MslEmitResult result = emit_msl(program);
    ARMIGO_CHECK(!result.ok());
    ARMIGO_CHECK(result.kernel.source.empty());
    ARMIGO_CHECK(result.kernel.bindings.empty());
    ARMIGO_CHECK_EQ(result.diagnostics.size(), 1u);
    if (!result.diagnostics.empty()) {
        ARMIGO_CHECK_EQ(result.diagnostics[0].code,
                        DiagnosticCode::operand_out_of_range);
    }

    program = scale_bias_program();
    program.entry_point = "float4";
    ARMIGO_CHECK(!emit_msl(program).ok());
}

